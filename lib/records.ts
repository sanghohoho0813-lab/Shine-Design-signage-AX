/** 특정 키워드가 들어간 실적 건수 — 홈 통계 밴드가 실제 데이터에서 값을 가져온다 */
export function countRecords(re: RegExp) {
  return BUSINESS_RECORDS.reduce((n, g) => n + g.items.filter((i) => re.test(i)).length, 0);
}

export const KOROAD_COUNT = countRecords(/한국도로교통공단/);
export const MEDICAL_COUNT = countRecords(/병원|보건소|의료원|산후조리원/);

export function sectorCounts() {
  const all = BUSINESS_RECORDS.flatMap((g) => g.items);
  const counts = new Map(RECORD_SECTORS.map((s) => [s.label, 0]));
  for (const item of all) {
    const hit = RECORD_SECTORS.find((s) => s.test.test(item));
    if (hit) counts.set(hit.label, counts.get(hit.label)! + 1);
  }
  return RECORD_SECTORS.map((s) => ({ label: s.label, count: counts.get(s.label)! }));
}
